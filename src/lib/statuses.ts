export const STATUSES = [
  { id: "saved", label: "Saved", color: "bg-slate-100 text-slate-700 dark:bg-slate-800 dark:text-slate-200" },
  { id: "applied", label: "Applied", color: "bg-blue-100 text-blue-800 dark:bg-blue-950 dark:text-blue-200" },
  { id: "oa", label: "Online Assessment", color: "bg-violet-100 text-violet-800 dark:bg-violet-950 dark:text-violet-200" },
  { id: "interview", label: "Interviewing", color: "bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-200" },
  { id: "offer", label: "Offer", color: "bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-200" },
  { id: "rejected", label: "Rejected", color: "bg-rose-100 text-rose-800 dark:bg-rose-950 dark:text-rose-200" },
  { id: "ghosted", label: "Ghosted", color: "bg-zinc-200 text-zinc-600 dark:bg-zinc-800 dark:text-zinc-400" },
] as const;

export type Status = (typeof STATUSES)[number]["id"];

export function isStatus(value: unknown): value is Status {
  return STATUSES.some((s) => s.id === value);
}

export function statusInfo(id: Status) {
  return STATUSES.find((s) => s.id === id)!;
}

export type Application = {
  id: number;
  company: string;
  role: string;
  url: string | null;
  location: string | null;
  source: string | null;
  status: Status;
  applied_date: string | null; // YYYY-MM-DD
  notes: string | null;
  description: string | null;
  match_score: number | null;
  match_json: string | null; // serialized Match from lib/match.ts
  matched_at: string | null;
  created_at: string;
  updated_at: string;
  doc_count?: number;
};

export const DOCUMENT_KINDS = [
  { id: "resume", label: "Resume" },
  { id: "cover_letter", label: "Cover letter" },
  { id: "other", label: "Other" },
] as const;

// Keep in sync with MIME_TYPES in lib/documents.ts.
export const ACCEPTED_FILE_TYPES = ".pdf,.doc,.docx,.odt,.rtf,.txt,.md";

export type DocumentKind = (typeof DOCUMENT_KINDS)[number]["id"];

export function isDocumentKind(value: unknown): value is DocumentKind {
  return DOCUMENT_KINDS.some((k) => k.id === value);
}

export type AppDocument = {
  id: number;
  application_id: number;
  kind: DocumentKind;
  filename: string; // original name shown to the user
  stored_name: string; // name on disk, generated by us
  mime_type: string;
  size: number;
  created_at: string;
};

export function scoreColor(score: number) {
  if (score >= 80) return "bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-200";
  if (score >= 60) return "bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-200";
  return "bg-rose-100 text-rose-800 dark:bg-rose-950 dark:text-rose-200";
}

// Wishlist = "Saved" jobs, best match first; unscored last, newest first.
export function wishlistJobs(apps: Application[]): Application[] {
  return apps
    .filter((a) => a.status === "saved")
    .sort((a, b) => (b.match_score ?? -1) - (a.match_score ?? -1) || b.created_at.localeCompare(a.created_at));
}
